#!/usr/bin/env node
/**
 * Regenerates `src/validators/index.ts`, the static registry of per-country checksum
 * modules. A static barrel lets bundlers (webpack, Wrangler/esbuild) include every
 * validator without the dynamic `require()` that breaks non-Node targets.
 *
 * Usage: node scripts/generate-validators-index.js [--check]
 *   --check  exit 1 if the committed file is out of date (used by tests/CI)
 */
const fs = require('fs');
const path = require('path');

const validatorsDir = path.resolve(__dirname, '..', 'src', 'validators');
const outFile = path.join(validatorsDir, 'index.ts');

const codes = fs
    .readdirSync(validatorsDir)
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
    .map((file) => file.slice(0, -'.ts'.length))
    .sort();

const lines = [
    '// Generated by scripts/generate-validators-index.js — do not edit by hand.',
    '',
];

for (const code of codes) {
    lines.push(`import * as ${code} from './${code}';`);
}

lines.push(
    '',
    'export interface ValidatorModule {',
    '    [key: string]: (input: string, debug?: boolean) => boolean | Promise<boolean>;',
    '}',
    '',
    'export const validators: Record<string, ValidatorModule> = {'
);

for (const code of codes) {
    lines.push(`    ${code}: ${code} as ValidatorModule,`);
}

lines.push('};', '');

const generated = lines.join('\n');

if (process.argv.includes('--check')) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (current !== generated) {
        console.error('src/validators/index.ts is out of date. Run: node scripts/generate-validators-index.js');
        process.exit(1);
    }
    console.log(`src/validators/index.ts is up to date (${codes.length} validators).`);
    process.exit(0);
}

fs.writeFileSync(outFile, generated);
console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${codes.length} validators).`);
